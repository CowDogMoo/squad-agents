#!/usr/bin/env python3
"""Validate, stage, and run the agent regression evals with `claude plugin eval`.

Each case lives in evals/<case>/ as a `claude plugin eval` case.yaml plus a
`fixture` link to the codebase the agent works on (an agent's testdata/
directory). The agents load skills that ship in the squad-skills plugin, so
the evals cannot run against this repository as it stands. `stage` builds one
plugin that holds both:

    <dest>/squad-agents/
        .claude-plugin/plugin.json   name only: no hooks, MCP servers, commands
        agents/<agent>.md            each agents/*.md, links resolved
        skills/<skill>/              every skill of a squad-skills checkout
        evals/<case>/case.yaml       the case, unchanged
        evals/<case>/fixture/        the fixture, copied
        evals/<case>/scaffold.sh     copies the fixture into the run's cwd

`run` then calls `claude plugin eval` on the staged plugin. It needs
--scaffold (the scaffold is generated here, never taken from a case) and
grants Bash, Edit, and Write, which the agents need to build and fix code.

  agent_evals.py validate
      check every case (no secrets, no model calls; runs in pytest)
  agent_evals.py stage --skills-dir DIR --dest DIR
      build the plugin above from this checkout and a squad-skills checkout
  agent_evals.py run --skills-dir DIR [--model M] [--runs N]
                     [--ablation none|with-without] [--case GLOB] [--out DIR]
      stage into a temporary directory and run the evals there

Model choice: every agent says `model: inherit`, so a subagent runs on the
model the case runs on. `--model` therefore compares models for every agent
at once; evals/README.md has the commands and what a result must show before
an agent's `model:` changes.
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVALS = ROOT / "evals"
AGENTS = ROOT / "agents"
PLUGIN = "squad-agents"
FIXTURE = "fixture"
SCAFFOLD = "scaffold.sh"
DEFAULT_MODEL = "claude-sonnet-5-5"
DEFAULT_JUDGE = "claude-sonnet-5-5"
GRANTED_TOOLS = ["Bash", "Edit", "Write"]
# The agent a case drives, named in its prompt as squad-agents:<agent>.
AGENT_REF = re.compile(rf"\b{PLUGIN}:([a-z0-9-]+)\b")
# Never copied into a staged skill or fixture.
IGNORED = {"__pycache__", ".DS_Store", "results", ".git"}
SCAFFOLD_SCRIPT = """\
#!/usr/bin/env bash
# Generated by scripts/agent_evals.py stage; not part of any case.
# Copies this case's fixture into the run's working directory and commits it,
# so `git diff` in the run shows only the agent's changes. A Go fixture's
# modules are downloaded here, before the agent's sandbox starts, so the
# agent can build with GOPROXY=off.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
cp -R "$here/fixture/." .
if [ -f go.mod ]; then
	go mod download
fi
git init -q
git add -A .
git -c user.name=agent-evals -c user.email=agent-evals@example.invalid \\
	commit -q -m "fixture"
"""


def load_yaml(path: Path) -> object:
    import yaml

    return yaml.safe_load(path.read_text(encoding="utf-8"))


def agent_names() -> set[str]:
    return {p.stem for p in AGENTS.glob("*.md")}


def case_dirs() -> list[Path]:
    return sorted(p.parent for p in EVALS.glob("*/case.yaml"))


def check_case(case_dir: Path, agents: set[str]) -> list[str]:
    """Return the problems with one case (empty when valid).

    claude plugin eval validates the full schema when it runs; this catches
    what would make a case unrunnable or meaningless before any model call.
    """
    try:
        case = load_yaml(case_dir / "case.yaml")
    except Exception as exc:
        return [f"case.yaml does not parse: {exc}"]
    if not isinstance(case, dict):
        return ["case.yaml must be a mapping"]

    errors = []
    if case.get("name") != case_dir.name:
        errors.append(f"name {case.get('name')!r} does not match the directory {case_dir.name!r}")
    if not isinstance(case.get("schema_version"), str):
        errors.append('schema_version must be a string such as "1.0"')
    if (case.get("context") or {}).get("scaffold_script") != SCAFFOLD:
        errors.append(f"context.scaffold_script must be {SCAFFOLD!r}; stage generates it")
    if (case_dir / SCAFFOLD).exists():
        errors.append(f"{SCAFFOLD} must not be checked in; stage generates it")
    fixture = case_dir / FIXTURE
    if not fixture.is_dir():
        errors.append(f"{FIXTURE} must link to a fixture directory")
    elif fixture.is_symlink():
        target = fixture.resolve()
        if not target.is_relative_to(ROOT):
            errors.append(f"{FIXTURE} resolves outside the repository: {target}")

    execution = case.get("execution") or {}
    prompt = execution.get("prompt")
    if not isinstance(prompt, str) or not prompt.strip():
        errors.append("execution.prompt is missing")
    else:
        named = AGENT_REF.findall(prompt)
        if not named:
            errors.append(f"execution.prompt must name the agent as {PLUGIN}:<agent>")
        for name in named:
            if name not in agents:
                errors.append(f"execution.prompt names {PLUGIN}:{name}, which is not in agents/")
    env = execution.get("env") or {}
    for key in env:
        if not str(key).startswith("EVAL_"):
            errors.append(
                f"execution.env sets {key}: claude plugin eval accepts only EVAL_* keys "
                "from a case; the runner sets the toolchain environment"
            )
    tools = execution.get("allowed_tools") or []
    if any(t not in tools for t in GRANTED_TOOLS):
        errors.append(
            f"execution.allowed_tools must include {GRANTED_TOOLS}: the agents build and edit code"
        )

    graders = case.get("graders")
    if not isinstance(graders, list) or not graders:
        errors.append("graders must be a non-empty list")
    else:
        names = [g.get("name") for g in graders if isinstance(g, dict)]
        if len(names) != len(set(names)):
            errors.append("grader names must be unique")
        if all(isinstance(g, dict) and g.get("type") == "tool_used" for g in graders):
            errors.append(
                "grade outcomes: at least one grader must be something other than tool_used"
            )
        for g in graders:
            if not isinstance(g, dict):
                errors.append("every grader must be a mapping")
                continue
            target = g.get("target")
            if isinstance(target, dict) and target.get("source") == "file":
                rel = target.get("path", "")
                if fixture.is_dir() and not (fixture / rel).is_file():
                    errors.append(f"grader {g.get('name')}: {rel} is not a file in the fixture")
            pattern = g.get("pattern") if g.get("type") == "regex" else g.get("input_match")
            if isinstance(pattern, str):
                try:
                    # Python reads the subset these patterns use the same way
                    # JavaScript does; a pattern Python rejects is suspect.
                    re.compile(pattern)
                except re.error as exc:
                    errors.append(f"grader {g.get('name')}: pattern does not compile: {exc}")
    return errors


def cmd_validate(_args: argparse.Namespace) -> int:
    agents = agent_names()
    failed = False
    cases = case_dirs()
    if not cases:
        print("::error::no cases under evals/")
        return 1
    for case_dir in cases:
        errors = check_case(case_dir, agents)
        for err in errors:
            print(f"::error file=evals/{case_dir.name}/case.yaml::{err}")
        failed = failed or bool(errors)
        if not errors:
            print(f"  ✓ evals/{case_dir.name}")
    for path in sorted(EVALS.iterdir()):
        if path.is_dir() and not (path / "case.yaml").is_file() and path.name not in IGNORED:
            print(f"::error file=evals/{path.name}::directory has no case.yaml")
            failed = True
    if failed:
        return 1
    print("✓ All agent eval cases are valid")
    return 0


def copy_tree(src: Path, dest: Path) -> None:
    shutil.copytree(src, dest, symlinks=False, ignore=shutil.ignore_patterns(*IGNORED))


def skill_folders(skills_dir: Path) -> dict[str, Path]:
    """Every skill in a squad-skills checkout, from its plugin's category list."""
    manifest = json.loads(
        (skills_dir / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8")
    )
    found = {}
    for category in manifest["skills"]:
        for skill_md in sorted((skills_dir / category).glob("*/SKILL.md")):
            if not skill_md.parent.name.startswith((".", "_")):
                found[skill_md.parent.name] = skill_md.parent
    return found


def stage(skills_dir: Path, dest: Path, cases: list[Path] | None = None) -> Path:
    """Build the eval plugin under dest and return its path."""
    plugin = dest / PLUGIN
    if plugin.exists():
        raise SystemExit(f"{plugin} already exists; refusing to stage over it")
    (plugin / ".claude-plugin").mkdir(parents=True)
    (plugin / ".claude-plugin" / "plugin.json").write_text(
        json.dumps({"name": PLUGIN}) + "\n", encoding="utf-8"
    )
    (plugin / "agents").mkdir()
    for agent in sorted(AGENTS.glob("*.md")):
        shutil.copyfile(agent.resolve(), plugin / "agents" / agent.name)
    for name, src in skill_folders(skills_dir).items():
        # A skill's evals/ holds its own expectations; the agents never need it.
        shutil.copytree(
            src,
            plugin / "skills" / name,
            symlinks=False,
            ignore=shutil.ignore_patterns(*IGNORED, "evals"),
        )
    for case_dir in cases if cases is not None else case_dirs():
        out = plugin / "evals" / case_dir.name
        out.mkdir(parents=True)
        shutil.copyfile(case_dir / "case.yaml", out / "case.yaml")
        copy_tree(case_dir / FIXTURE, out / FIXTURE)
        (out / SCAFFOLD).write_text(SCAFFOLD_SCRIPT, encoding="utf-8")
        (out / SCAFFOLD).chmod(0o755)
    return plugin


def cmd_stage(args: argparse.Namespace) -> int:
    plugin = stage(Path(args.skills_dir), Path(args.dest))
    print(f"✓ staged {plugin}")
    return 0


def toolchain_path() -> str:
    """PATH for the run, with each toolchain's real bin directory first.

    claude plugin eval gives the agent a throwaway HOME. Version-manager shims
    (mise, asdf) read their config from HOME, so under it `go` resolves to
    nothing; the toolchain's own bin directory still works.
    """
    dirs = []
    try:
        # `go` from PATH on purpose: this asks the operator's own toolchain.
        goroot = subprocess.run(
            ["go", "env", "GOROOT"],  # noqa: S607
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        if goroot:
            dirs.append(str(Path(goroot) / "bin"))
    except (OSError, subprocess.CalledProcessError):
        pass
    return os.pathsep.join([*dirs, os.environ.get("PATH", "")])


def run_env() -> dict[str, str]:
    """The environment claude plugin eval and the agents under it run with.

    A case may only set EVAL_* variables, so the toolchain settings live here.
    The scaffold downloads a fixture's Go modules before the run (it gets a
    minimal environment of its own, without these), so the agent builds
    offline: GOPROXY=off makes a missing module fail fast instead of hanging
    on a network the sandbox blocks, and GOTOOLCHAIN=local stops Go from
    fetching a newer toolchain.
    """
    return {
        **os.environ,
        "PATH": toolchain_path(),
        "GOTOOLCHAIN": "local",
        "GOPROXY": "off",
    }


def eval_command(plugin: Path, out: Path, args: argparse.Namespace) -> list[str]:
    granted = [t for t in GRANTED_TOOLS if not (args.without_bash and t == "Bash")]
    cmd = [
        "claude",
        "plugin",
        "eval",
        str(plugin),
        "--trust-plugin",
        "--scaffold",
        "--allow-tools",
        *granted,
        "--ablation",
        args.ablation,
        "--model",
        args.model,
        "--judge-model",
        args.judge_model,
        "--runs",
        str(args.runs),
        "--concurrency",
        str(args.concurrency),
        "--threshold",
        "0",
        "--no-publish",
        "--output-dir",
        str(out),
        "--json",
        str(out / "result.json"),
        "--report",
        str(out / "report.html"),
    ]
    if args.case:
        cmd += ["--case", args.case]
    if args.max_cost_usd:
        cmd += ["--max-cost-usd", str(args.max_cost_usd)]
    return cmd


def cmd_run(args: argparse.Namespace) -> int:
    selected = [c for c in case_dirs() if not args.case or fnmatch.fnmatch(c.name, args.case)]
    if not selected:
        print(f"::error::no case matches {args.case!r}")
        return 1
    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="agent-evals-") as tmp:
        plugin = stage(Path(args.skills_dir), Path(tmp), selected)
        cmd = eval_command(plugin, out, args)
        print("Running:", " ".join(cmd), flush=True)
        # The command is built here from fixed flags and parsed arguments.
        code = subprocess.run(cmd, env=run_env(), check=False).returncode  # noqa: S603
    print(f"Results: {out / 'result.json'} (HTML report: {out / 'report.html'})")
    return code


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("validate", help="check every case under evals/")

    stage_cmd = sub.add_parser("stage", help="build the eval plugin")
    stage_cmd.add_argument("--skills-dir", required=True, help="a squad-skills checkout")
    stage_cmd.add_argument("--dest", required=True, help="directory to build the plugin in")

    run = sub.add_parser("run", help="stage, then run claude plugin eval")
    run.add_argument("--skills-dir", required=True, help="a squad-skills checkout")
    run.add_argument(
        "--model", default=DEFAULT_MODEL, help="model for every case (agents inherit it)"
    )
    run.add_argument("--judge-model", default=DEFAULT_JUDGE, help="model for the LLM graders")
    run.add_argument("--runs", type=int, default=3, help="runs per case")
    run.add_argument(
        "--ablation",
        choices=("none", "with-without"),
        default="none",
        help="with-without also runs each case without the plugin and reports the delta",
    )
    run.add_argument("--case", help="only cases whose directory name matches this glob")
    run.add_argument("--concurrency", type=int, default=1, help="agent runs at once (1-8)")
    run.add_argument("--max-cost-usd", type=float, help="abort when the run's cost passes this")
    run.add_argument("--out", default="agent-evals-results", help="directory for the results")
    run.add_argument(
        "--without-bash",
        action="store_true",
        help="do not grant Bash: claude plugin eval refuses Bash-granting runs on a machine whose "
        "~/.aws config uses credential_process; cases that build or test then score lower",
    )

    args = parser.parse_args(argv)
    return {"validate": cmd_validate, "stage": cmd_stage, "run": cmd_run}[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
